#!/usr/bin/env bash
# Refreshes the two generated inputs of the legacy IT harness module (ADR 014, MBD §9):
#  1. src/generated/java: the POJOs the Maven module listing-integration-test generates from its own
#     src/test/raml/json/schema with the framework's pojo-generation-plugin (no Gradle port of that
#     generator exists; see listing-domain-event-spring/build.gradle).
#  2. legacy-it-dependencies.txt: the Maven module's resolved test classpath (exact versions,
#     resolved non-transitively by Gradle), minus the listing reactor modules (replaced by the
#     Gradle projects) and the JUnit 4/5, OpenEJB/TomEE, DeltaSpike test-control, HSQLDB and
#     MSSQL jars (persistence-test and JUnit-engine jars the ITs do not use; JUnit comes from the
#     Gradle build), the Linux/macOS-x86 netty native transports, and android-json (it shadows
#     org.json's unchecked JSONException, which Maven's classpath order happened to pick).
# Run after changing listing-integration-test/pom.xml or its schemas. Offline by default.
set -euo pipefail
cd "$(dirname "$0")/.."
module=listing-integration-test-legacy
mvn ${MVN_ARGS:--o} -q -B -pl listing-integration-test generate-sources
rm -rf "$module/src/generated/java"
mkdir -p "$module/src/generated/java"
rsync -a listing-integration-test/target/generated-sources/ "$module/src/generated/java/"

list=$(mktemp)
mvn ${MVN_ARGS:--o} -q -B -Dstyle.color=never -pl listing-integration-test dependency:list \
    -DincludeScope=test -DoutputFile="$list" -Dmdep.outputScope=false >/dev/null
{
  echo "# Generated by refresh-legacy-inputs.sh from listing-integration-test/pom.xml (mvn dependency:list, test scope)."
  echo "# group:artifact:version[:classifier] — resolved by Gradle with transitive=false. Do not edit by hand."
  sed -E 's/\x1b\[[0-9;]*m//g; s/ -- module.*//; s/^ +//' "$list" \
    | grep -E '^[a-z][^ ]*:[^ ]+$' \
    | grep -vE '^(uk\.gov\.moj\.cpp\.listing|io\.netty:netty-transport-native-(epoll|kqueue)|com\.vaadin\.external\.google:android-json|junit|org\.junit\.[a-z]+|org\.apache\.tomee[a-z.]*|org\.apache\.openejb[a-z.]*|org\.apache\.openwebbeans|org\.apache\.xbean|org\.apache\.deltaspike\.(cdictrl|modules)|org\.hsqldb|com\.microsoft\.sqlserver|org\.apache\.geronimo\.components|org\.apache\.bval):' \
    | awk -F: '{ if (NF == 5) print $1":"$2":"$5":"$4; else print $1":"$2":"$4 }' \
    | sort -u
} > "$module/legacy-it-dependencies.txt"
rm -f "$list"
echo "Vendored $(find "$module/src/generated/java" -name '*.java' | wc -l | tr -d ' ') POJOs; $(grep -vc '^#' "$module/legacy-it-dependencies.txt") dependencies"
